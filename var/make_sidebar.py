#!/usr/bin/env python3
"""Rebuild the module lists in _data/sidebars/main.yml from the pages themselves.

Each sidebar section that has a `folder:` key gets its `subitems` regenerated from
pages/<folder>/*.md, sorted by `order` then title. Everything else in the file
(titles, icons, descriptions, other sections) is kept as written.

CI runs this before every build, so new modules never need a hand edit to the
sidebar, and two pull requests adding modules never conflict on this file.
Run it locally before `jekyll serve` to see new modules in the sidebar.
"""
import pathlib, yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
path = ROOT / "_data/sidebars/main.yml"
side = yaml.safe_load(path.read_text())


def front(p):
    text = p.read_text(encoding="utf-8")
    return yaml.safe_load(text.split("---", 2)[1]) if text.startswith("---") else {}


changed = 0
for sec in side.get("subitems", []):
    folder = sec.get("folder")
    if not folder:
        continue
    mods = []
    for f in sorted((ROOT / "pages" / folder).glob("*.md")):
        fm = front(f) or {}
        # menus use `nav_title`, or the title before a " – " subtitle
        label = fm.get("nav_title") or str(fm.get("title", f.stem)).split(" – ")[0].strip()
        mods.append((fm.get("order", 999), label, "/" + fm.get("page_id", f.stem)))
    items = [{"title": t, "url": u} for _, t, u in sorted(mods)]
    if items != sec.get("subitems"):
        changed += 1
    sec["subitems"] = items

path.write_text("# Module lists under sections with `folder:` are generated by var/make_sidebar.py.\n"
                + yaml.safe_dump(side, sort_keys=False, allow_unicode=True, width=1000))
print(f"sidebar: {changed} section(s) updated")
