#!/usr/bin/env python3
"""Generate one stub page per CPP from _data/cpps.json (mirrored from EOSC EDEN WP1).

Stubs hold front matter only; the `cpp` layout renders everything else from the data
file. Re-run after syncing the CPP data. Do not edit the generated pages by hand.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = json.loads((ROOT / "_data" / "cpps.json").read_text(encoding="utf-8"))
out_dir = ROOT / "pages" / "cpps"
out_dir.mkdir(parents=True, exist_ok=True)

for cpp in data["cpps"]:
    slug = cpp["id"].lower().replace("-", "_")
    description = cpp["shortDefinition"].replace('"', "'")
    (out_dir / f"{slug}.md").write_text(
        "---\n"
        "# Generated by var/make_cpp_pages.py from _data/cpps.json. Do not edit.\n"
        f'title: "{cpp["id"]} {cpp["label"]}"\n'
        f'description: "{description}"\n'
        f"cpp: {cpp['id']}\n"
        f"page_id: {slug}\n"
        "---\n",
        encoding="utf-8",
    )
print(f"Wrote {len(data['cpps'])} CPP pages to {out_dir.relative_to(ROOT)}")
